# Split the one-line transcript into sections by heading strings (first occurrence after previous).
import json, re, os, sys
t = open(os.path.join(os.path.dirname(__file__), "source.txt"), encoding="utf-8-sig").read()
SEC = [  # (part, heading text as it appears)
 ("0", "Предисловие."), ("0", "Введение."),
 ("1", "Один. Голос как инструмент."), ("1", "Происхождение голоса, происхождение языка"), ("1","Зеркальные нейроны"),
 ("1", "Эпигенетика"), ("1", "Человек звучащий."), ("1", "Ухо."), ("1","Человеческий мозг."),
 ("1", "Голоса калеки."), ("1", "Конферансье, преподаватели"), ("1", "Голос, оказывается, обладает пленительной силой."),
 ("1", "Хорошие вибрации."), ("1", "Чары прошлого."), ("1", "Харизма."),
 ("2", "2. Голос власти."), ("2", "Король заикается."), ("2", "Приручить телевизор."), ("2","Руки тоже говорят."),
 ("2", "Существует ли алгоритм голоса лидера?"), ("2", "Особый случай."), ("2", "Большие дети."), ("2", "Код нашего голоса."),
 ("2", "Каждой эпохе свои голоса."),
 ("3", "Главное невидимо."), ("3", "Бог и голоса."),
 ("4", "Голос как зрелище."), ("4", "Имитатор."), ("4", "Костраты."), ("4","Мандраж и стресс."), ("4","Портрет профессионала."),
 ("5", "Тихий голос."), ("5", "Эвмениды Эсхила."),
 ("6", "Заключение."), ("x", "Благодарности."),
]
pos, out = 0, []
for part, h in SEC:
    i = t.find(h, pos)
    if i < 0: sys.exit(f"not found: {h}")
    out.append([part, h.rstrip("."), i]); pos = i + 1
for k, s in enumerate(out):
    end = out[k+1][2] if k+1 < len(out) else len(t)
    s.append(end); s.append(len(t[s[2]:end].split()))
json.dump(out, open(os.path.join(os.path.dirname(__file__), "sections.json"), "w"), ensure_ascii=False, indent=1)
for p,h,a,b,w in out: print(f"{p} {a:7d} {w:6d} слов ~{w/130:4.0f} мин чтения вслух  {h}")
